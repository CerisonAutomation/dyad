import { describe, expect, it } from "vitest";
import {
  applyIdentityOverride,
  buildIdentityColumnQuery,
  describeIdentityColumnError,
  isIdentityColumnError,
  parseIdentityColumns,
  parseInsertForIdentityCheck,
} from "./execute_sql_identity";

const ALWAYS = [{ name: "id", identity: "a" as const }];
const BY_DEFAULT = [{ name: "id", identity: "d" as const }];

describe("parseInsertForIdentityCheck", () => {
  it("parses a simple insert with a column list", () => {
    const parsed = parseInsertForIdentityCheck(
      "INSERT INTO t (id, name) VALUES (1,'x')",
    );
    expect(parsed).not.toBeNull();
    expect(parsed?.schema).toBeNull();
    expect(parsed?.table).toBe("t");
    expect(parsed?.columns).toEqual(["id", "name"]);
  });

  it("keeps a schema-qualified table", () => {
    const parsed = parseInsertForIdentityCheck(
      "insert into public.users (id, name) values (1, 'x')",
    );
    expect(parsed?.schema).toBe("public");
    expect(parsed?.table).toBe("users");
  });

  it("refuses statements it cannot rewrite safely", () => {
    // A CTE, a multi-statement script, an insert without a column list and a
    // non-insert statement must all run unchanged.
    expect(
      parseInsertForIdentityCheck(
        "WITH x AS (SELECT 1) INSERT INTO t (id) VALUES (1)",
      ),
    ).toBeNull();
    expect(
      parseInsertForIdentityCheck("INSERT INTO t (id) VALUES (1); SELECT 1;"),
    ).toBeNull();
    expect(
      parseInsertForIdentityCheck("INSERT INTO t VALUES (1,'x')"),
    ).toBeNull();
    expect(parseInsertForIdentityCheck("UPDATE t SET id = 1")).toBeNull();
    expect(parseInsertForIdentityCheck("SELECT * FROM t")).toBeNull();
  });

  it("refuses a quoted or otherwise complex table name", () => {
    expect(
      parseInsertForIdentityCheck('INSERT INTO "My Table" (id) VALUES (1)'),
    ).toBeNull();
    expect(
      parseInsertForIdentityCheck("INSERT INTO db.public.t (id) VALUES (1)"),
    ).toBeNull();
  });
});

describe("applyIdentityOverride", () => {
  it("injects OVERRIDING SYSTEM VALUE for a GENERATED ALWAYS column", () => {
    const sql = "INSERT INTO t (id, name) VALUES (1,'x')";
    const parsed = parseInsertForIdentityCheck(sql);
    expect(parsed).not.toBeNull();
    const rewrite = applyIdentityOverride(sql, parsed!, ALWAYS);
    expect(rewrite?.sql).toBe(
      "INSERT INTO t (id, name) OVERRIDING SYSTEM VALUE VALUES (1,'x')",
    );
    expect(rewrite?.overriddenColumns).toEqual(["id"]);
  });

  it("preserves the rest of the statement byte-for-byte", () => {
    const sql =
      "-- seed\nINSERT  INTO public.t\n  ( id , name )\nVALUES (1,'x')  -- end";
    const parsed = parseInsertForIdentityCheck(sql);
    expect(parsed).not.toBeNull();
    const rewrite = applyIdentityOverride(sql, parsed!, ALWAYS);
    expect(rewrite?.sql).toBe(
      "-- seed\nINSERT  INTO public.t\n  ( id , name ) OVERRIDING SYSTEM VALUE\nVALUES (1,'x')  -- end",
    );
  });

  it("leaves a GENERATED BY DEFAULT column alone", () => {
    const sql = "INSERT INTO t (id, name) VALUES (1,'x')";
    const parsed = parseInsertForIdentityCheck(sql);
    expect(applyIdentityOverride(sql, parsed!, BY_DEFAULT)).toBeNull();
  });

  it("leaves a column list without an identity column alone", () => {
    const sql = "INSERT INTO t (name) VALUES ('x')";
    const parsed = parseInsertForIdentityCheck(sql);
    expect(applyIdentityOverride(sql, parsed!, ALWAYS)).toBeNull();
  });
});

describe("buildIdentityColumnQuery", () => {
  it("resolves the table the same way the insert does", () => {
    const query = buildIdentityColumnQuery({ schema: null, table: "t" });
    expect(query).toContain("pg_catalog");
    expect(query).toContain("attidentity");
    expect(query).toContain(`to_regclass('"t"')`);

    const qualified = buildIdentityColumnQuery({
      schema: "public",
      table: "t",
    });
    expect(qualified).toContain(`to_regclass('"public"."t"')`);
  });

  it("refuses to inline an unsafe identifier", () => {
    expect(
      buildIdentityColumnQuery({
        schema: null,
        table: "t'); DROP TABLE x; --",
      }),
    ).toBeNull();
  });
});

describe("parseIdentityColumns", () => {
  it("reads the identity kind from the catalog result", () => {
    expect(
      parseIdentityColumns(
        JSON.stringify([{ attname: "id", attidentity: "a" }]),
      ),
    ).toEqual([{ name: "id", identity: "a" }]);
    expect(
      parseIdentityColumns(
        JSON.stringify([{ attname: "id", attidentity: "d" }]),
      ),
    ).toEqual([{ name: "id", identity: "d" }]);
  });

  it("treats an unknown identity kind as BY DEFAULT so nothing is overridden", () => {
    expect(parseIdentityColumns(JSON.stringify([{ attname: "id" }]))).toEqual([
      { name: "id", identity: "d" },
    ]);
  });

  it("returns nothing for an unparseable result", () => {
    expect(parseIdentityColumns("not json")).toEqual([]);
  });
});

describe("identity column errors", () => {
  const rawError = new Error(
    'Failed to run query: Bad Request (400): ERROR: 428C9: cannot insert a non-DEFAULT value into column "id"\nDETAIL: Column "id" is an identity column defined as GENERATED ALWAYS.\nHINT: Use OVERRIDING SYSTEM VALUE to override.',
  );

  it("detects the identity column rejection", () => {
    expect(isIdentityColumnError(rawError)).toBe(true);
    expect(isIdentityColumnError(new Error("relation does not exist"))).toBe(
      false,
    );
  });

  it("names the cause and the fix", () => {
    const message = describeIdentityColumnError(rawError);
    expect(message).toContain('column "id"');
    expect(message).toContain("GENERATED ALWAYS");
    expect(message).toContain("OVERRIDING SYSTEM VALUE");
    expect(message).not.toContain("Bad Request (400)");
  });
});
