/**
 * Identity-column handling for the local-agent `execute_sql` tool.
 *
 * PostgreSQL refuses `INSERT INTO t (id, ...) VALUES (...)` when `id` is an
 * identity column defined as `GENERATED ALWAYS AS IDENTITY` (SQLSTATE 428C9).
 * The tool used to surface that raw error, so the model had no idea what to
 * change. These helpers detect the statement shape, look the identity columns
 * up in `pg_catalog`, and inject `OVERRIDING SYSTEM VALUE` — the injected
 * clause is the only change, everything else is preserved byte-for-byte.
 *
 * `OVERRIDING SYSTEM VALUE` is the PostgreSQL-documented way to supply an
 * explicit value for a `GENERATED ALWAYS` identity column: "any values
 * supplied for identity columns will override the default sequence-generated
 * values" (https://www.postgresql.org/docs/current/sql-insert.html). It is
 * ignored by PostgreSQL when the table has no applicable identity column.
 *
 * Everything here is deliberately conservative: when a statement cannot be
 * parsed with certainty, the caller runs it unchanged. A wrong rewrite is
 * worse than no rewrite.
 */

/** SQLSTATE PostgreSQL raises for an explicit value on a GENERATED ALWAYS column. */
const IDENTITY_ERROR_SQLSTATE = "428C9";

/**
 * `a` = GENERATED ALWAYS, `d` = GENERATED BY DEFAULT.
 * Only `a` needs the `OVERRIDING SYSTEM VALUE` override; `d` already accepts
 * an explicit value.
 */
export type IdentityKind = "a" | "d";

export interface IdentityColumn {
  /** Column name exactly as PostgreSQL stores it in `pg_attribute.attname`. */
  name: string;
  identity: IdentityKind;
}

export interface ParsedInsertStatement {
  /** Schema of a schema-qualified table reference, otherwise null. */
  schema: string | null;
  /** Table name, folded to lower case the way PostgreSQL folds unquoted names. */
  table: string;
  /** Column names: folded when unquoted, verbatim when double-quoted. */
  columns: string[];
  /** Index in the original SQL just past the closing paren of the column list. */
  overrideInsertIndex: number;
}

/** Identifiers we are willing to inline into a catalog query. */
const SAFE_IDENTIFIER = /^[A-Za-z_][A-Za-z0-9_$]*$/;

const IDENTIFIER_CHAR = /[A-Za-z0-9_$]/;

function isWhitespace(char: string): boolean {
  return (
    char === " " ||
    char === "\t" ||
    char === "\n" ||
    char === "\r" ||
    char === "\f" ||
    char === "\v"
  );
}

/** Skip whitespace, line comments and block comments. */
function skipWhitespaceAndComments(sql: string, pos: number): number {
  let index = pos;
  while (index < sql.length) {
    const char = sql[index];
    if (isWhitespace(char)) {
      index++;
      continue;
    }
    if (char === "-" && sql[index + 1] === "-") {
      const newline = sql.indexOf("\n", index);
      index = newline === -1 ? sql.length : newline + 1;
      continue;
    }
    if (char === "/" && sql[index + 1] === "*") {
      const end = sql.indexOf("*/", index + 2);
      index = end === -1 ? sql.length : end + 2;
      continue;
    }
    break;
  }
  return index;
}

/** Match a keyword at `pos`; the next character must not extend the word. */
function matchKeyword(sql: string, pos: number, word: string): number {
  if (sql.slice(pos, pos + word.length).toLowerCase() !== word.toLowerCase()) {
    return -1;
  }
  const next = sql[pos + word.length];
  if (next && IDENTIFIER_CHAR.test(next)) {
    return -1;
  }
  return pos + word.length;
}

/** Read an unquoted identifier; PostgreSQL folds these to lower case. */
function readIdentifier(
  sql: string,
  pos: number,
): { value: string; end: number } | null {
  let end = pos;
  while (end < sql.length && IDENTIFIER_CHAR.test(sql[end])) {
    end++;
  }
  if (end === pos) {
    return null;
  }
  const raw = sql.slice(pos, end);
  if (!/^[A-Za-z_]/.test(raw)) {
    return null;
  }
  return { value: raw.toLowerCase(), end };
}

/** Read a double-quoted identifier; the name is used verbatim. */
function readQuotedIdentifier(
  sql: string,
  pos: number,
): { value: string; end: number } | null {
  if (sql[pos] !== '"') {
    return null;
  }
  let index = pos + 1;
  let value = "";
  while (index < sql.length) {
    if (sql[index] === '"') {
      if (sql[index + 1] === '"') {
        value += '"';
        index += 2;
        continue;
      }
      return { value, end: index + 1 };
    }
    value += sql[index];
    index++;
  }
  return null;
}

/**
 * Positions of semicolons that are not inside a string literal, a quoted
 * identifier, a dollar-quoted body or a comment.
 */
function scanTopLevelSemicolons(sql: string): number[] {
  const positions: number[] = [];
  let index = 0;
  while (index < sql.length) {
    const char = sql[index];
    if (char === "-" && sql[index + 1] === "-") {
      const newline = sql.indexOf("\n", index);
      index = newline === -1 ? sql.length : newline + 1;
      continue;
    }
    if (char === "/" && sql[index + 1] === "*") {
      const end = sql.indexOf("*/", index + 2);
      index = end === -1 ? sql.length : end + 2;
      continue;
    }
    if (char === "'" || char === '"') {
      const quote = char;
      index++;
      while (index < sql.length) {
        if (sql[index] === quote) {
          if (sql[index + 1] === quote) {
            index += 2;
            continue;
          }
          index++;
          break;
        }
        index++;
      }
      continue;
    }
    if (char === "$") {
      const tag = /^\$([A-Za-z_][A-Za-z0-9_]*)?\$/.exec(sql.slice(index));
      if (tag) {
        const end = sql.indexOf(tag[0], index + tag[0].length);
        index = end === -1 ? sql.length : end + tag[0].length;
        continue;
      }
    }
    if (char === ";") {
      positions.push(index);
      index++;
      continue;
    }
    index++;
  }
  return positions;
}

/** True when the SQL holds at most one statement. */
function isSingleStatement(sql: string): boolean {
  const semicolons = scanTopLevelSemicolons(sql);
  if (semicolons.length > 1) {
    return false;
  }
  if (semicolons.length === 1) {
    return skipWhitespaceAndComments(sql, semicolons[0] + 1) === sql.length;
  }
  return true;
}

/**
 * Parse the target of a table reference. Quoted or otherwise non-trivial
 * names are rejected so an unparseable table never reaches a catalog query.
 */
function readTableReference(
  sql: string,
  pos: number,
): { schema: string | null; table: string; end: number } | null {
  const first = readIdentifier(sql, pos);
  if (!first) {
    return null;
  }
  let schema: string | null = null;
  let table = first.value;
  let end = first.end;
  const afterFirst = skipWhitespaceAndComments(sql, end);
  if (sql[afterFirst] === ".") {
    const afterDot = skipWhitespaceAndComments(sql, afterFirst + 1);
    const second = readIdentifier(sql, afterDot);
    if (!second) {
      return null;
    }
    schema = table;
    table = second.value;
    end = second.end;
    if (sql[skipWhitespaceAndComments(sql, end)] === ".") {
      // schema.table.column style reference — not a plain table target.
      return null;
    }
  }
  return { schema, table, end };
}

function readColumnList(
  sql: string,
  pos: number,
): { columns: string[]; end: number } | null {
  let index = pos + 1;
  const columns: string[] = [];
  for (;;) {
    index = skipWhitespaceAndComments(sql, index);
    const quoted = readQuotedIdentifier(sql, index);
    if (quoted) {
      columns.push(quoted.value);
      index = quoted.end;
    } else {
      const identifier = readIdentifier(sql, index);
      if (!identifier) {
        return null;
      }
      columns.push(identifier.value);
      index = identifier.end;
    }
    index = skipWhitespaceAndComments(sql, index);
    if (sql[index] === ",") {
      index++;
      continue;
    }
    if (sql[index] === ")") {
      return { columns, end: index + 1 };
    }
    return null;
  }
}

/**
 * Parse a single-statement `INSERT INTO <table> (<columns>) <values|select>`
 * that could be rewritten with `OVERRIDING SYSTEM VALUE`.
 *
 * Returns null (meaning: run the statement unchanged) for anything else:
 * CTEs, multi-statement SQL, quoted or otherwise unresolvable table names,
 * inserts without an explicit column list, and shapes we do not recognise.
 */
export function parseInsertForIdentityCheck(
  sql: string,
): ParsedInsertStatement | null {
  if (!isSingleStatement(sql)) {
    return null;
  }
  let pos = skipWhitespaceAndComments(sql, 0);
  const afterInsert = matchKeyword(sql, pos, "INSERT");
  if (afterInsert < 0) {
    return null;
  }
  pos = skipWhitespaceAndComments(sql, afterInsert);
  const afterInto = matchKeyword(sql, pos, "INTO");
  if (afterInto < 0) {
    return null;
  }
  pos = skipWhitespaceAndComments(sql, afterInto);
  const target = readTableReference(sql, pos);
  if (!target) {
    return null;
  }
  pos = skipWhitespaceAndComments(sql, target.end);
  if (sql[pos] !== "(") {
    // No explicit column list: there is nothing to override.
    return null;
  }
  const columnList = readColumnList(sql, pos);
  if (!columnList || columnList.columns.length === 0) {
    return null;
  }
  const keywordPos = skipWhitespaceAndComments(sql, columnList.end);
  const keyword = readIdentifier(sql, keywordPos);
  if (!keyword) {
    return null;
  }
  if (keyword.value === "default") {
    const valuesPos = skipWhitespaceAndComments(sql, keyword.end);
    const values = readIdentifier(sql, valuesPos);
    if (!values || values.value !== "values") {
      return null;
    }
  } else if (keyword.value !== "values" && keyword.value !== "select") {
    // e.g. an existing OVERRIDING clause or a shape we do not handle.
    return null;
  }
  return {
    schema: target.schema,
    table: target.table,
    columns: columnList.columns,
    overrideInsertIndex: columnList.end,
  };
}

/**
 * Build the single catalog query that resolves the identity columns of the
 * insert target.
 *
 * `to_regclass` resolves the table exactly the way PostgreSQL resolves the
 * name in the INSERT (schema-qualified name, otherwise via `search_path`), so
 * an unqualified table name cannot be matched against the wrong table.
 *
 * The identifiers are validated before they are inlined, so the query never
 * carries user-authored SQL.
 */
export function buildIdentityColumnQuery(target: {
  schema: string | null;
  table: string;
}): string | null {
  if (!SAFE_IDENTIFIER.test(target.table)) {
    return null;
  }
  if (target.schema !== null && !SAFE_IDENTIFIER.test(target.schema)) {
    return null;
  }
  const qualified = target.schema
    ? `"${target.schema}"."${target.table}"`
    : `"${target.table}"`;
  return [
    "SELECT a.attname, a.attidentity",
    "FROM pg_catalog.pg_attribute a",
    `WHERE a.attrelid = pg_catalog.to_regclass('${qualified}')::pg_catalog.oid`,
    "  AND a.attidentity <> ''",
    "  AND a.attnum > 0",
    "  AND NOT a.attisdropped",
  ].join("\n");
}

function extractRows(value: unknown): unknown[] {
  if (Array.isArray(value)) {
    return value;
  }
  if (value && typeof value === "object") {
    const record = value as Record<string, unknown>;
    for (const key of ["rows", "result", "data"]) {
      if (Array.isArray(record[key])) {
        return record[key] as unknown[];
      }
    }
  }
  return [];
}

function readStringField(
  record: Record<string, unknown>,
  keys: string[],
): string | undefined {
  for (const key of keys) {
    const value = record[key];
    if (typeof value === "string" && value.length > 0) {
      return value;
    }
  }
  return undefined;
}

/**
 * Parse the JSON result of the catalog query into identity columns.
 *
 * A column is only treated as `GENERATED ALWAYS` when the catalog actually
 * says so; anything else is treated as `GENERATED BY DEFAULT` so an
 * unexpected response can never trigger an override.
 */
export function parseIdentityColumns(raw: string): IdentityColumn[] {
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    return [];
  }
  const columns: IdentityColumn[] = [];
  for (const row of extractRows(parsed)) {
    if (!row || typeof row !== "object") {
      continue;
    }
    const record = row as Record<string, unknown>;
    const name = readStringField(record, ["attname", "column_name", "name"]);
    if (!name) {
      continue;
    }
    const identity = readStringField(record, [
      "attidentity",
      "identity_type",
      "identity",
    ]);
    columns.push({
      name,
      identity: identity?.trim().toLowerCase() === "a" ? "a" : "d",
    });
  }
  return columns;
}

/**
 * Inject `OVERRIDING SYSTEM VALUE` when the statement supplies a value for a
 * `GENERATED ALWAYS` identity column.
 *
 * `GENERATED BY DEFAULT` columns are left alone — they already accept an
 * explicit value.
 */
export function applyIdentityOverride(
  sql: string,
  parsed: ParsedInsertStatement,
  identityColumns: IdentityColumn[],
): { sql: string; overriddenColumns: string[] } | null {
  const alwaysColumns = new Set(
    identityColumns
      .filter((column) => column.identity === "a")
      .map((column) => column.name),
  );
  const overriddenColumns = parsed.columns.filter((column) =>
    alwaysColumns.has(column),
  );
  if (overriddenColumns.length === 0) {
    return null;
  }
  const clause = " OVERRIDING SYSTEM VALUE";
  return {
    sql:
      sql.slice(0, parsed.overrideInsertIndex) +
      clause +
      sql.slice(parsed.overrideInsertIndex),
    overriddenColumns,
  };
}

function extractErrorMessage(error: unknown): string {
  if (error instanceof Error) {
    return error.message;
  }
  if (typeof error === "string") {
    return error;
  }
  return "";
}

/** True when the failure is PostgreSQL's identity-column rejection. */
export function isIdentityColumnError(error: unknown): boolean {
  const message = extractErrorMessage(error);
  if (!message) {
    return false;
  }
  if (message.includes(IDENTITY_ERROR_SQLSTATE)) {
    return true;
  }
  return /identity column/i.test(message) && /generated always/i.test(message);
}

/** The identity column named by a PostgreSQL identity-column error, if any. */
export function extractIdentityColumnName(error: unknown): string | undefined {
  const message = extractErrorMessage(error);
  const explicit =
    /cannot insert a non-default value into column "([^"]+)"/i.exec(message);
  if (explicit) {
    return explicit[1];
  }
  const detailed =
    /column "([^"]+)" is an identity column defined as generated always/i.exec(
      message,
    );
  return detailed?.[1];
}

/**
 * The PostgreSQL part of a provider error, without the provider's HTTP
 * wrapper (`Failed to run query: Bad Request (400): ...`).
 */
function extractDatabaseDetail(message: string): string {
  const errorIndex = message.indexOf("ERROR:");
  if (errorIndex >= 0) {
    return message.slice(errorIndex);
  }
  return message;
}

/**
 * Explain an identity-column failure in terms of the cause and the fix, so the
 * model sees what to change instead of a raw "Bad Request (400)" blob.
 */
export function describeIdentityColumnError(error: unknown): string {
  const message = extractErrorMessage(error);
  const column = extractIdentityColumnName(error);
  const target = column ? `column "${column}"` : "an identity column";
  const fix = column
    ? `either drop "${column}" from the INSERT column list so the identity sequence assigns it, or add OVERRIDING SYSTEM VALUE after the column list to force the value you passed`
    : "either drop the identity column from the INSERT column list so the identity sequence assigns it, or add OVERRIDING SYSTEM VALUE after the column list to force the value you passed";
  return `PostgreSQL rejected the INSERT because ${target} is an identity column defined as GENERATED ALWAYS, so it does not accept an explicit value. Fix the statement: ${fix}. Database error: ${extractDatabaseDetail(message)}`;
}
